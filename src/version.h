#ifndef DAGRIM_VERSION_H
#define DAGRIM_VERSION_H

#define DAGRIM_VERSION_MAJOR 0
#define DAGRIM_VERSION_MINOR 0
#define DAGRIM_VERSION_PATCH 1
#define DAGRIM_VERSION_BUILD 0
#define DAGRIM_STRINGIFY_IMPL(x) #x
#define DAGRIM_STRINGIFY(x) DAGRIM_STRINGIFY_IMPL(x)
#define DAGRIM_WIDE_IMPL(x) L##x
#define DAGRIM_WIDE(x) DAGRIM_WIDE_IMPL(x)
#define DAGRIM_VERSION_STRING DAGRIM_STRINGIFY(DAGRIM_VERSION_MAJOR) "." DAGRIM_STRINGIFY(DAGRIM_VERSION_MINOR) "." DAGRIM_STRINGIFY(DAGRIM_VERSION_PATCH)
#define DAGRIM_VERSION_WSTRING DAGRIM_WIDE(DAGRIM_STRINGIFY(DAGRIM_VERSION_MAJOR)) L"." DAGRIM_WIDE(DAGRIM_STRINGIFY(DAGRIM_VERSION_MINOR)) L"." DAGRIM_WIDE(DAGRIM_STRINGIFY(DAGRIM_VERSION_PATCH))
#define DAGRIM_VERSION_TUPLE DAGRIM_VERSION_MAJOR,DAGRIM_VERSION_MINOR,DAGRIM_VERSION_PATCH,DAGRIM_VERSION_BUILD

#endif
